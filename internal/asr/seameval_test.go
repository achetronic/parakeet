//go:build seameval

// Package asr's seam cost evaluator. Build-tag gated so it never runs in the
// normal test suite (it needs ONNX Runtime, the models, and the seam-eval
// dataset). It measures, exhaustively, where long-audio chunking spends WER:
//
//   - human WER: chunked transcription vs the human ground truth (expected.txt),
//     matching the prior full_wer.py numbers.
//   - oracle WER: chunked transcription vs the SAME model transcribing each clip
//     individually (single pass). Both share frontend/encoder/decoder, so the
//     only difference is chunking; this isolates the pure seam+chunk cost.
//   - error histogram by distance-to-nearest-seam, and a near/far S/D/I split.
//
// Dataset is generated by /tmp/make_seameval.py (LibriSpeech test-clean):
//
//	SEAMEVAL_DIR=/tmp/seameval PARAKEET_MODELS=./models \
//	go test -tags=seameval -run TestSeamEval -v ./internal/asr/
package asr

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"strings"
	"testing"

	"parakeet/internal/audio"
)

// manifestClip is one entry of /tmp/seameval/manifest.json.
type manifestClip struct {
	Index    int     `json:"index"`
	Wav      string  `json:"wav"`
	Text     string  `json:"text"`
	Start    float64 `json:"start"`    // seconds offset inside concat.wav
	Duration float64 `json:"duration"` // seconds
}

// humanWordRe is the tokenizer that matches the prior full_wer.py normalizer.
var humanWordRe = regexp.MustCompile("[a-zäöüßáéíóúñàèìòùâêîôûãõç0-9']+")

// normHuman lowercases and tokenizes arbitrary reference/hypothesis text.
func normHuman(s string) []string {
	return humanWordRe.FindAllString(strings.ToLower(s), -1)
}

// normOracleWord normalizes a single ASR word for self-comparison: lowercased,
// with outer punctuation trimmed, keeping interior apostrophes/hyphens so the
// model's own word segmentation aligns 1:1 with itself.
func normOracleWord(s string) string {
	s = strings.ToLower(s)
	return strings.TrimFunc(s, func(r rune) bool {
		switch {
		case r >= 'a' && r <= 'z':
			return false
		case r >= '0' && r <= '9':
			return false
		case r == '\'' || r == '-':
			return false
		}
		return true
	})
}

func TestSeamEval(t *testing.T) {
	dir := os.Getenv("SEAMEVAL_DIR")
	if dir == "" {
		dir = "/tmp/seameval"
	}
	modelsDir := os.Getenv("PARAKEET_MODELS")
	if modelsDir == "" {
		modelsDir = "./models"
	}
	band := 5.0 // seconds either side of a seam counts as "near"

	man, err := os.ReadFile(dir + "/manifest.json")
	if err != nil {
		t.Fatalf("manifest not found (%v); run /tmp/make_seameval.py first", err)
	}
	var clips []manifestClip
	if err := json.Unmarshal(man, &clips); err != nil {
		t.Fatalf("parse manifest: %v", err)
	}

	tr, err := NewTranscriber(modelsDir, 2, Options{
		Chunk: ChunkConfig{
			Enabled:        true,
			Seconds:        DefaultChunkSeconds,
			OverlapSeconds: DefaultChunkOverlapSeconds,
		},
	})
	if err != nil {
		t.Fatalf("new transcriber (needs ONNX Runtime + models): %v", err)
	}
	defer tr.Close()

	ctx := context.Background()

	// --- reference: transcribe each clip individually (single pass, no seams) ---
	var refWords []Word // absolute times (clip.Start + per-clip offset)
	for _, c := range clips {
		data, err := os.ReadFile(c.Wav)
		if err != nil {
			t.Fatalf("read clip %d: %v", c.Index, err)
		}
		samples, err := audio.Load(data, nil)
		if err != nil {
			t.Fatalf("decode clip %d: %v", c.Index, err)
		}
		ws, err := tr.TranscribeWordsSamples(ctx, samples)
		if err != nil {
			t.Fatalf("transcribe clip %d: %v", c.Index, err)
		}
		for _, w := range ws {
			refWords = append(refWords, Word{
				Text:  w.Text,
				Start: w.Start + c.Start,
				End:   w.End + c.Start,
			})
		}
	}

	// --- hypothesis + seam plan over the concatenated audio ---
	data, err := os.ReadFile(dir + "/concat.wav")
	if err != nil {
		t.Fatalf("read concat: %v", err)
	}
	samples, err := audio.Load(data, nil)
	if err != nil {
		t.Fatalf("decode concat: %v", err)
	}
	hypWords, err := tr.TranscribeWordsSamples(ctx, samples)
	if err != nil {
		t.Fatalf("transcribe concat: %v", err)
	}

	seams := seamSeconds(tr, samples)

	// Clip-join boundaries: every clip (except the first) is preceded by the
	// 0.5s synthetic silence inserted by make_seameval.py. If deletions cluster
	// here rather than at chunk seams, the residual cost is a concatenation
	// artifact, not a long-audio chunking problem.
	clipBounds := make([]float64, 0, len(clips)-1)
	for _, c := range clips {
		if c.Index > 0 {
			clipBounds = append(clipBounds, c.Start)
		}
	}

	// --- human WER (token level) ---
	expectedB, err := os.ReadFile(dir + "/expected.txt")
	if err != nil {
		t.Fatalf("read expected.txt: %v", err)
	}
	humanRef := normHuman(string(expectedB))
	var humanHypText strings.Builder
	for _, w := range hypWords {
		humanHypText.WriteString(w.Text)
		humanHypText.WriteString(" ")
	}
	humanHyp := normHuman(humanHypText.String())
	humanDist, humanS, humanD, humanI := editOps(humanRef, humanHyp)
	t.Logf("HUMAN  WER = %.2f%%  (S=%d D=%d I=%d / ref=%d hyp=%d)",
		percent(humanDist, len(humanRef)), humanS, humanD, humanI,
		len(humanRef), len(humanHyp))

	// --- oracle WER (word level, self-comparison) ---
	refN := make([]string, len(refWords))
	hypN := make([]string, len(hypWords))
	for i, w := range refWords {
		refN[i] = normOracleWord(w.Text)
	}
	for i, w := range hypWords {
		hypN[i] = normOracleWord(w.Text)
	}
	oracleDist, oracleS, oracleD, oracleI := editOps(refN, hypN)
	t.Logf("ORACLE WER = %.2f%%  (S=%d D=%d I=%d / ref=%d hyp=%d)",
		percent(oracleDist, len(refN)), oracleS, oracleD, oracleI,
		len(refN), len(hypN))

	t.Logf("seams (%d): %v", len(seams), seams)

	// --- align oracle words to classify and localize each error ---
	ops := align(refN, hypN)

	// histogram: 1s buckets up to 60s, then a 60+ overflow bucket.
	const bucketN = 61 // index 0..59 = [i,i+1), index 60 = 60+
	type bin struct{ s, d, i int }
	hist := make([]bin, bucketN)
	histClip := make([]bin, bucketN)
	near := bin{}
	far := bin{}
	refNear := 0
	refFar := 0
	type deletion struct {
		text            string
		t, dSeam, dClip float64
	}
	var deletions []deletion

	for _, w := range refWords {
		if distToSeam(w.Start, seams) <= band {
			refNear++
		} else {
			refFar++
		}
	}

	for _, op := range ops {
		if op.kind == 0 {
			continue
		}
		var t float64
		switch op.kind {
		case 1: // sub -> use hypothesis word time
			t = hypWords[op.h].Start
		case 2: // del -> use reference word time
			t = refWords[op.r].Start
		case 3: // ins -> use hypothesis word time
			t = hypWords[op.h].Start
		}
		d := distToSeam(t, seams)
		bi := int(d)
		if bi >= bucketN-1 {
			bi = bucketN - 1
		}
		dc := distToSeam(t, clipBounds)
		bci := int(dc)
		if bci >= bucketN-1 {
			bci = bucketN - 1
		}
		switch op.kind {
		case 1:
			hist[bi].s++
			histClip[bci].s++
		case 2:
			hist[bi].d++
			histClip[bci].d++
			deletions = append(deletions, deletion{
				text:  refWords[op.r].Text,
				t:     t,
				dSeam: d,
				dClip: dc,
			})
		case 3:
			hist[bi].i++
			histClip[bci].i++
		}
		if d <= band {
			switch op.kind {
			case 1:
				near.s++
			case 2:
				near.d++
			case 3:
				near.i++
			}
		} else {
			switch op.kind {
			case 1:
				far.s++
			case 2:
				far.d++
			case 3:
				far.i++
			}
		}
	}

	nearTot := near.s + near.d + near.i
	farTot := far.s + far.d + far.i
	t.Logf("NEAR (<=%.0fs of a seam): S=%d D=%d I=%d (total=%d) over %d ref words",
		band, near.s, near.d, near.i, nearTot, refNear)
	t.Logf("FAR  (>%.0fs from a seam): S=%d D=%d I=%d (total=%d) over %d ref words",
		band, far.s, far.d, far.i, farTot, refFar)
	t.Logf("localized WER near=%.2f%% far=%.2f%%",
		percent(nearTot, refNear), percent(farTot, refFar))

	t.Log("ERROR HISTOGRAM (distance-to-seam buckets, S|D|I):")
	for b := 0; b < bucketN; b++ {
		lo, hi := b, b+1
		label := fmt.Sprintf(">=%ds", b)
		if b < bucketN-1 {
			label = fmt.Sprintf("%d-%ds", lo, hi)
		}
		total := hist[b].s + hist[b].d + hist[b].i
		if total > 0 {
			t.Logf("  %8s: %3d  (S=%d D=%d I=%d)", label, total, hist[b].s, hist[b].d, hist[b].i)
		}
	}

	t.Log("ERROR HISTOGRAM (distance-to-clip-boundary buckets, S|D|I):")
	for b := 0; b < bucketN; b++ {
		lo, hi := b, b+1
		label := fmt.Sprintf(">=%ds", b)
		if b < bucketN-1 {
			label = fmt.Sprintf("%d-%ds", lo, hi)
		}
		total := histClip[b].s + histClip[b].d + histClip[b].i
		if total > 0 {
			t.Logf("  %8s: %3d  (S=%d D=%d I=%d)", label, total, histClip[b].s, histClip[b].d, histClip[b].i)
		}
	}

	t.Log("DELETIONS (word | time | dSeam | dClip):")
	for _, dl := range deletions {
		t.Logf("  %-20s t=%6.1fs  dSeam=%5.1fs  dClip=%5.1fs",
			dl.text, dl.t, dl.dSeam, dl.dClip)
	}
}

// seamSeconds returns the long-audio chunk seam positions in seconds by
// re-planning the chunks exactly as transcribe does (same features, same
// boundary cascade). Seam i is the emit boundary between window i and i+1.
func seamSeconds(tr *Transcriber, samples []float32) []float64 {
	features := tr.mel.Extract(samples)
	subsampling := int64(tr.config.SubsamplingFactor)
	oracle := tr.newBoundaryOracle(features, samples)
	plan, err := planForAudioWithBoundaries(
		int64(len(features)), tr.chunkFrames, tr.overlapFrames, subsampling, tr.maxEncoderFrames, true, oracle)
	if err != nil {
		return nil
	}
	fps := float64(tr.mel.FramesPerSecond())
	seams := make([]float64, 0, len(plan)-1)
	for i := 0; i < len(plan)-1; i++ {
		seams = append(seams, float64(plan[i].emitEnd)/fps)
	}
	return seams
}

// distToSeam returns the absolute distance in seconds from t to the nearest
// seam (0 when there are no seams).
func distToSeam(t float64, seams []float64) float64 {
	if len(seams) == 0 {
		return 0
	}
	best := absf(t - seams[0])
	for _, s := range seams[1:] {
		if d := absf(t - s); d < best {
			best = d
		}
	}
	return best
}

func absf(x float64) float64 {
	if x < 0 {
		return -x
	}
	return x
}

func percent(dist, ref int) float64 {
	if ref == 0 {
		return 0
	}
	return float64(dist) * 100.0 / float64(ref)
}

// editOps returns Levenshtein distance and its S/D/I breakdown.
func editOps(ref, hyp []string) (dist, subs, dels, inss int) {
	ops := align(ref, hyp)
	for _, op := range ops {
		switch op.kind {
		case 1:
			subs++
		case 2:
			dels++
		case 3:
			inss++
		}
	}
	return subs + dels + inss, subs, dels, inss
}

type op struct {
	kind int // 0 match, 1 sub, 2 del, 3 ins
	r, h int // indices; -1 when absent
}

// align computes a standard word-level Levenshtein alignment with backtrace.
func align(ref, hyp []string) []op {
	nr, nh := len(ref), len(hyp)
	d := make([][]int, nr+1)
	for i := range d {
		d[i] = make([]int, nh+1)
	}
	for i := 0; i <= nr; i++ {
		d[i][0] = i
	}
	for j := 0; j <= nh; j++ {
		d[0][j] = j
	}
	for i := 1; i <= nr; i++ {
		for j := 1; j <= nh; j++ {
			cost := 0
			if ref[i-1] != hyp[j-1] {
				cost = 1
			}
			d[i][j] = min3(d[i-1][j]+1, d[i][j-1]+1, d[i-1][j-1]+cost)
		}
	}
	ops := make([]op, 0, nr+nh)
	i, j := nr, nh
	for i > 0 || j > 0 {
		switch {
		case i > 0 && j > 0 && ref[i-1] == hyp[j-1] && d[i][j] == d[i-1][j-1]:
			ops = append(ops, op{0, i - 1, j - 1})
			i--
			j--
		case i > 0 && j > 0 && d[i][j] == d[i-1][j-1]+1:
			ops = append(ops, op{1, i - 1, j - 1})
			i--
			j--
		case i > 0 && d[i][j] == d[i-1][j]+1:
			ops = append(ops, op{2, i - 1, -1})
			i--
		default:
			ops = append(ops, op{3, -1, j - 1})
			j--
		}
	}
	for a, b := 0, len(ops)-1; a < b; a, b = a+1, b-1 {
		ops[a], ops[b] = ops[b], ops[a]
	}
	return ops
}

func min3(a, b, c int) int {
	if a < b {
		if a < c {
			return a
		}
		return c
	}
	if b < c {
		return b
	}
	return c
}
